import { ValidationError } from "../types.js";

/**
 * 文本 PGM（P2）导入/导出。
 * 支持：# 注释、任意空白分隔、魔数 P2、宽度 高度、maxval（必须为 255）。
 * 多帧/掩膜通过自定义注释标记扩展（见下），也可只交换纯 PGM 像素主体。
 */

export function encodePgm(pixels: number[][]): string {
  const h = pixels.length;
  const w = h === 0 ? 0 : pixels[0]!.length;
  const lines: string[] = ["P2", `# generated by seamcarve-gray`, `${w} ${h}`, "255"];
  for (let r = 0; r < h; r++) {
    lines.push(pixels[r]!.join(" "));
  }
  return lines.join("\n") + "\n";
}

function tokenize(text: string): string[] {
  const lines = text.split(/\r?\n/);
  const kept: string[] = [];
  for (const raw of lines) {
    const hash = raw.indexOf("#");
    const line = hash >= 0 ? raw.slice(0, hash) : raw;
    const parts = line.trim().split(/\s+/).filter((s) => s.length > 0);
    kept.push(...parts);
  }
  return kept;
}

export function parsePgm(text: string): { width: number; height: number; pixels: number[][] } {
  const tokens = tokenize(text);
  if (tokens[0] !== "P2") {
    throw new ValidationError("只支持文本 PGM（魔数 P2）");
  }
  const width = Number(tokens[1]);
  const height = Number(tokens[2]);
  const maxval = Number(tokens[3]);
  if (!Number.isInteger(width) || !Number.isInteger(height) || width <= 0 || height <= 0) {
    throw new ValidationError("PGM 宽高必须为正整数");
  }
  if (maxval !== 255) {
    throw new ValidationError(`仅支持 maxval=255 的 8 位 PGM，实际为 ${maxval}`);
  }
  const data = tokens.slice(4).map(Number);
  if (data.length !== width * height) {
    throw new ValidationError(
      `PGM 像素数 ${data.length} 与声明尺寸 ${width}x${height}=${width * height} 不符`,
    );
  }
  const pixels: number[][] = [];
  for (let r = 0; r < height; r++) {
    const row: number[] = [];
    for (let c = 0; c < width; c++) {
      const v = data[r * width + c]!;
      if (!Number.isInteger(v) || v < 0 || v > 255) {
        throw new ValidationError(`PGM 像素 (${r},${c}) 不在 0..255`);
      }
      row.push(v);
    }
    pixels.push(row);
  }
  return { width, height, pixels };
}

