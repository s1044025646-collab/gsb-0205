import { AppError } from '../errors.js';
import type { Matrix } from '../types.js';

/**
 * 文本 PGM（Netpbm P2）支持。
 * 二进制 P5 不在支持范围内（本服务按“文本 PGM”要求实现）。
 */

export function encodeP2(matrix: Matrix): string {
  const height = matrix.length;
  const width = matrix[0]!.length;
  const lines: string[] = ['P2', `# generated by seamcarve-grayscale`, `${width} ${height}`, '255'];
  for (let r = 0; r < height; r++) {
    lines.push(matrix[r]!.join(' '));
  }
  return lines.join('\n') + '\n';
}

interface P2Parse {
  width: number;
  height: number;
  matrix: Matrix;
}

/** 词法切分：P2 文件中 # 起始为注释，其余按空白拆分。 */
function tokenizeP2(text: string): string[] {
  const cleaned = text
    .split(/\r?\n/)
    .map((line) => {
      const hash = line.indexOf('#');
      return hash >= 0 ? line.slice(0, hash) : line;
    })
    .join('\n');
  return cleaned.split(/\s+/).filter((token) => token.length > 0);
}

export function parseP2(text: string): P2Parse {
  const tokens = tokenizeP2(text);
  if (tokens[0] !== 'P2') {
    throw new AppError('PGM_BAD_MAGIC', `仅支持文本 PGM（魔数 P2），收到 ${tokens[0] ?? '空内容'}`);
  }
  const width = Number(tokens[1]);
  const height = Number(tokens[2]);
  const maxVal = Number(tokens[3]);
  if (!Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) {
    throw new AppError('PGM_BAD_HEADER', 'PGM 头部宽高必须为正整数');
  }
  if (!Number.isInteger(maxVal) || maxVal <= 0 || maxVal > 65535) {
  throw new AppError('PGM_BAD_MAXVAL', 'PGM maxval 非法（仅支持 1..65535，本服务按 8 位校验像素）');
  }
  const expected = width * height;
  const dataTokens = tokens.slice(4);
  if (dataTokens.length < expected) {
    throw new AppError('PGM_TRUNCATED', `像素数量不足：期望 ${expected}，实际 ${dataTokens.length}`);
  }
  const matrix: Matrix = [];
  let index = 4;
  for (let r = 0; r < height; r++) {
    const row: number[] = [];
    for (let c = 0; c < width; c++) {
      const raw = tokens[index]!;
      const value = Number(raw);
      index++;
      if (!Number.isInteger(value)) {
        throw new AppError('PGM_BAD_PIXEL', `位置 (${r},${c}) 不是整数: ${raw}`);
      }
      if (value < 0 || value > 255) {
        throw new AppError('PGM_PIXEL_OUT_OF_RANGE', `位置 (${r},${c})=${value} 超出 8 位 [0,255]`, 422);
      }
      row.push(value);
    }
    matrix.push(row);
  }
  return { width, height, matrix };
}
